"""Assemble a narrated walkthrough from actual browser screenshots.
Requires Pillow, imageio-ffmpeg and WAVs generated by narrate.ps1.
This is a screenshot walkthrough, not a continuous screen recording.
"""
import json,subprocess,wave,sys
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
sys.path.insert(0,str(Path('.tools').resolve()))
import imageio_ffmpeg
root=Path('submission');work=root/'video-work';work.mkdir(exist_ok=True)
segments=json.loads((root/'walkthrough.json').read_text(encoding='utf-8'))
ff=imageio_ffmpeg.get_ffmpeg_exe();total=0
font=ImageFont.truetype('C:/Windows/Fonts/arialbd.ttf',29)
small=ImageFont.truetype('C:/Windows/Fonts/arial.ttf',21)
for i,s in enumerate(segments):
    screen=Image.open(root/'screenshots'/s['image']).convert('RGB');screen.thumbnail((1560,1080))
    canvas=Image.new('RGB',(1600,1200),'#F7F6F2');canvas.paste(screen,((1600-screen.width)//2,14))
    draw=ImageDraw.Draw(canvas);draw.rectangle((0,1095,1600,1200),fill='#1C1D1F')
    draw.text((30,1110),s['title'],font=font,fill='#F5C451');draw.text((30,1153),s['caption'],font=small,fill='white')
    draw.text((1510,1110),f'{i+1}/8',font=font,fill='#F5C451')
    image=work/f'{i:02}.png';canvas.save(image)
    wav=work/f'{i:02}.wav'
    with wave.open(str(wav)) as w:duration=w.getnframes()/w.getframerate()+0.8
    total+=duration
    subprocess.run([ff,'-y','-loglevel','error','-loop','1','-i',str(image),'-i',str(wav),'-t',str(duration),'-r','15','-c:v','libx264','-preset','fast','-tune','stillimage','-crf','24','-pix_fmt','yuv420p','-c:a','aac','-ar','44100','-ac','1','-af','apad',str(work/f'{i:02}.mp4')],check=True)
assert total<180,f'Video exceeds limit: {total}'
(work/'concat.txt').write_text('\n'.join(f"file '{i:02}.mp4'" for i in range(len(segments))),encoding='utf-8')
subprocess.run([ff,'-y','-loglevel','error','-f','concat','-safe','0','-i',str(work/'concat.txt'),'-c','copy','-movflags','+faststart',str(root/'venomlink-walkthrough.mp4')],check=True)
(root/'VIDEO_METADATA.json').write_text(json.dumps({'type':'Narrated walkthrough using actual browser screenshots; not continuous screen recording','durationSeconds':round(total,2),'width':1600,'height':1200,'providerStatus':'Unconfigured demo; no live AWS or Google results claimed','narration':'Windows Microsoft Zira synthetic narration'},indent=2),encoding='utf-8')
print(json.dumps({'durationSeconds':total,'file':str(root/'venomlink-walkthrough.mp4')}))
